#!/usr/bin/env node
// Generates src/api/schema.d.ts from the FastAPI backend's own OpenAPI
// schema (via openapi-typescript) — one source of truth between FastAPI and
// TypeScript, no hand-duplicated interfaces to drift out of sync.
//
//   npm run gen:api             # write src/api/schema.d.ts
//   npm run gen:api -- --check  # exit 1 if the committed file is stale
//
// Dumping app.openapi() directly (rather than curling a running server) means
// this works in CI with no `eda-rl serve` process to stand up.

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = fileURLToPath(new URL(".", import.meta.url));
const outPath = fileURLToPath(new URL("../src/api/schema.d.ts", import.meta.url));
const check = process.argv.includes("--check");

const pythonBin = process.env.EDA_RL_PYTHON || "python3";
const dumpScript =
  "import json; from eda_rl.api.server import app; print(json.dumps(app.openapi()))";

let openapiJson;
try {
  openapiJson = execFileSync(pythonBin, ["-c", dumpScript], {
    cwd: here,
    encoding: "utf-8",
    maxBuffer: 1024 * 1024 * 16,
  });
} catch (err) {
  console.error(
    `Could not dump the FastAPI OpenAPI schema via '${pythonBin} -c ...'. ` +
      "Is eda-rl installed with the [api] extra (pip install -e '.[api]')?"
  );
  console.error(err.message);
  process.exit(1);
}

const schema = JSON.parse(openapiJson);
const ast = await openapiTS(schema);
const contents =
  "// AUTO-GENERATED by `npm run gen:api` from the FastAPI OpenAPI schema.\n" +
  "// Do not hand-edit — run `npm run gen:api` after changing eda_rl/api/.\n\n" +
  astToString(ast);

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf-8") : null;
  if (current !== contents) {
    console.error("src/api/schema.d.ts is stale — run `npm run gen:api`.");
    process.exit(1);
  }
  console.log("src/api/schema.d.ts is up to date.");
} else {
  writeFileSync(outPath, contents);
  console.log(`wrote ${outPath}`);
}
